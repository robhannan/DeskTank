/// The field visualised over the tank.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FieldOverlay {
    /// A scalar ecology field.
    Scalar(desktank_sim::FieldKind),
    /// The water speed generated by filter outlets.
    Flow,
}

impl FieldOverlay {
    /// Parses the name used by capture and web settings.
    #[must_use]
    pub fn from_name(name: &str) -> Option<Self> {
        if name == "flow" {
            Some(Self::Flow)
        } else {
            desktank_sim::FieldKind::from_name(name).map(Self::Scalar)
        }
    }

    /// The stable name used by capture and web settings.
    #[must_use]
    pub fn name(self) -> &'static str {
        match self {
            Self::Scalar(kind) => kind.name(),
            Self::Flow => "flow",
        }
    }
}
